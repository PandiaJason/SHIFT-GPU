#!/usr/bin/env python3
"""
Generate 100% Empirical, Publication-Quality Figures for Elsevier SUSCOM.
All plots strictly reflect empirical CSV outputs generated by:
  scripts/run_strict_leakage_free_experiments.py

Author: Jason Pandian (Nehru Institute of Technology)
"""

import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

np.random.seed(42)
plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
plt.rcParams.update({
    "font.family": "serif",
    "font.size": 9,
    "axes.labelsize": 9.5,
    "axes.titlesize": 10.5,
    "xtick.labelsize": 8.5,
    "ytick.labelsize": 8.5,
    "legend.fontsize": 8,
    "figure.titlesize": 11,
    "lines.linewidth": 1.6,
    "lines.markersize": 5,
    "grid.alpha": 0.35,
    "grid.linestyle": "--",
})

c_adapt = "#1b9e77"    # Teal/Green: Proposed SHIFT-GPU (PICAN)
c_fixed = "#d95f02"    # Orange: Matched XGBoost Baseline
c_roofx = "#2b6cb0"    # Steel Blue: XGBoost + Roofline
c_event = "#7570b3"    # Purple: Oracle
c_gray  = "#666666"    # Neutral Gray: Roofline / Uniform Random
c_gold  = "#e6ab02"    # Amber: K-Means / Flat MLP

FIG_DIR = "paper/figures"
EXP_FIG_DIR = "experiments/figures"
os.makedirs(FIG_DIR, exist_ok=True)
os.makedirs(EXP_FIG_DIR, exist_ok=True)


def save_fig(name):
    plt.tight_layout()
    plt.savefig(os.path.join(FIG_DIR, name), dpi=300, bbox_inches="tight")
    plt.savefig(os.path.join(EXP_FIG_DIR, name), dpi=300, bbox_inches="tight")
    plt.close()


def main():
    df_preds = pd.read_csv("experiments/results/empirical_predictions.csv")
    df_fewshot = pd.read_csv("experiments/results/table_e5_active_few_shot.csv")
    df_rec = pd.read_csv("experiments/results/table_e6_decision_recommendations.csv")
    df_ablation = pd.read_csv("experiments/results/table_e7_ablations.csv")
    print(f"Loaded {len(df_preds)} empirical predictions across {df_preds['gpu_db_name'].nunique()} GPUs.")

    y_true_ms = df_preds["itl_true"].values * 1000.0
    y_pican_ms = df_preds["itl_pred_pican"].values * 1000.0
    y_xgb_ms = df_preds["itl_pred_xgb"].values * 1000.0
    y_xgbr_ms = df_preds["itl_pred_xgb_roof"].values * 1000.0
    y_roof_ms = df_preds["itl_roofline"].values * 1000.0

    err_pican = np.abs(y_true_ms - y_pican_ms) / y_true_ms * 100.0
    err_xgb = np.abs(y_true_ms - y_xgb_ms) / y_true_ms * 100.0
    err_xgbr = np.abs(y_true_ms - y_xgbr_ms) / y_true_ms * 100.0
    err_roof = np.abs(y_true_ms - y_roof_ms) / y_true_ms * 100.0

    md_pican = float(np.median(err_pican))
    md_xgb = float(np.median(err_xgb))
    md_xgbr = float(np.median(err_xgbr))
    md_roof = float(np.median(err_roof))

    # ==========================================================================
    # FIGURE 2: Parity & CDF
    # ==========================================================================
    print("Generating Figure 2...")
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 4.2))
    ax1 = axes[0]
    ax1.scatter(y_true_ms, y_xgb_ms, s=11, color=c_fixed, alpha=0.30, label=f"Matched XGBoost (MdAPE = {md_xgb:.2f}%)", rasterized=True)
    ax1.scatter(y_true_ms, y_pican_ms, s=13, color=c_adapt, alpha=0.50, label=f"SHIFT-GPU PICAN (MdAPE = {md_pican:.2f}%)", rasterized=True)
    lims = [min(y_true_ms.min(), y_pican_ms.min()) * 0.8, max(y_true_ms.max(), y_pican_ms.max()) * 1.2]
    ax1.plot(lims, lims, color="black", linestyle="--", linewidth=1.2, label=r"Ideal Parity ($y = \hat{y}$)")
    ax1.set_xscale("log"); ax1.set_yscale("log")
    ax1.set_xlim(lims); ax1.set_ylim(lims)
    ax1.set_xlabel(r"Measured Inter-Token Latency $T_{\mathrm{meas}}$ (ms) [log scale]")
    ax1.set_ylabel(r"Predicted Latency $\hat{T}$ (ms) [log scale]")
    ax1.set_title("(a) Zero-Shot Prediction Parity (4,163 Configurations)")
    ax1.legend(loc="upper left", framealpha=0.92, fontsize=7.8)

    ax2 = axes[1]
    cdf_y = np.linspace(0, 1, len(err_pican))
    ax2.plot(np.sort(err_pican), cdf_y, color=c_adapt, linewidth=2.0, label=f"SHIFT-GPU PICAN ({md_pican:.2f}%)")
    ax2.plot(np.sort(err_xgbr), cdf_y, color=c_roofx, linestyle="-.", linewidth=1.6, label=f"XGBoost + Roofline ({md_xgbr:.2f}%)")
    ax2.plot(np.sort(err_xgb), cdf_y, color=c_fixed, linestyle="--", linewidth=1.6, label=f"Matched XGBoost ({md_xgb:.2f}%)")
    ax2.plot(np.sort(err_roof), cdf_y, color=c_gray, linestyle=":", linewidth=1.5, label=f"Non-Learning Roofline ({md_roof:.2f}%)")
    ax2.set_xscale("log"); ax2.set_xlim(0.5, 200)
    ax2.set_xlabel("Relative Prediction Error (%) [log scale]")
    ax2.set_ylabel(r"Cumulative Probability $P(\mathrm{Error} \leq e)$")
    ax2.set_title("(b) Cumulative Error Distribution (Empirical CDF)")
    ax2.axvline(md_pican, color=c_adapt, linestyle="-.", alpha=0.6, linewidth=1.0)
    ax2.axvline(md_xgb, color=c_fixed, linestyle="-.", alpha=0.6, linewidth=1.0)
    ax2.legend(loc="upper left", framealpha=0.92, fontsize=7.8)
    save_fig("fig2_temporal_dynamics_panel.png")

    # ==========================================================================
    # FIGURE 3: Hardware Generalization & Shift Distance
    # ==========================================================================
    print("Generating Figure 3...")
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 4.2))
    rows_shift = []
    name_map = {
        "A100 SXM4 40 GB": "A100 SXM4", "Tesla T4": "Tesla T4", "A30 PCIe": "A30 PCIe",
        "Tesla V100 SXM2 32 GB": "V100 SXM2", "L4": "NVIDIA L4", "H100 NVL 94 GB": "H100 NVL",
        "L40S": "NVIDIA L40S", "H200 NVL": "H200 NVL",
    }
    for g, sub in df_preds.groupby("gpu_db_name"):
        rows_shift.append({
            "gpu": g, "short_name": name_map.get(g, g),
            "shift": sub["hw_shift_score"].iloc[0],
            "pican": float(np.median(np.abs(sub["itl_true"] - sub["itl_pred_pican"]) / sub["itl_true"]) * 100.0),
            "xgb": float(np.median(np.abs(sub["itl_true"] - sub["itl_pred_xgb"]) / sub["itl_true"]) * 100.0),
            "xgbr": float(np.median(np.abs(sub["itl_true"] - sub["itl_pred_xgb_roof"]) / sub["itl_true"]) * 100.0),
        })
    df_s = pd.DataFrame(rows_shift).sort_values("shift")

    ax = axes[0]
    x = np.arange(len(df_s))
    w = 0.27
    ax.bar(x - w, df_s["xgb"], w, label="Matched XGBoost", color=c_fixed, edgecolor="black", linewidth=0.5)
    ax.bar(x, df_s["xgbr"], w, label="XGBoost + Roofline", color=c_roofx, edgecolor="black", linewidth=0.5)
    ax.bar(x + w, df_s["pican"], w, label="SHIFT-GPU (PICAN)", color=c_adapt, edgecolor="black", linewidth=0.5)
    ax.set_xticks(x)
    ax.set_xticklabels(df_s["short_name"], rotation=30, ha="right", fontsize=8.2)
    ax.set_ylim(0, 21.5)
    ax.set_ylabel("Inter-Token Latency MdAPE (%)")
    ax.set_title("(a) Zero-Shot LOGO Error Across 8 GPUs")
    ax.legend(loc="upper left", framealpha=0.92, fontsize=7.8)

    ax = axes[1]
    ax.scatter(df_s["shift"], df_s["xgb"], s=65, color=c_fixed, marker="o", edgecolors="black", label="Matched XGBoost")
    ax.scatter(df_s["shift"], df_s["xgbr"], s=65, color=c_roofx, marker="s", edgecolors="black", label="XGBoost + Roofline")
    ax.scatter(df_s["shift"], df_s["pican"], s=80, color=c_adapt, marker="^", edgecolors="black", label="SHIFT-GPU (PICAN)")

    offsets = {
        "A100 SXM4": (18, -13), "Tesla T4": (24, -4), "A30 PCIe": (4, -12),
        "V100 SXM2": (24, -3), "NVIDIA L4": (6, -12), "H100 NVL": (5, -12),
        "NVIDIA L40S": (0, 8), "H200 NVL": (-14, -14),
    }
    for _, r in df_s.iterrows():
        ox, oy = offsets.get(r["short_name"], (0, 6))
        ax.annotate(r["short_name"], (r["shift"], r["pican"]), textcoords="offset points", xytext=(ox, oy), ha="center", fontsize=7.3)

    grid = np.linspace(df_s["shift"].min() * 0.9, df_s["shift"].max() * 1.05, 100)
    ax.plot(grid, np.poly1d(np.polyfit(df_s["shift"], df_s["xgb"], 1))(grid), color=c_fixed, linestyle="--", linewidth=1.2, alpha=0.7)
    ax.plot(grid, np.poly1d(np.polyfit(df_s["shift"], df_s["xgbr"], 1))(grid), color=c_roofx, linestyle="-.", linewidth=1.2, alpha=0.7)
    ax.plot(grid, np.poly1d(np.polyfit(df_s["shift"], df_s["pican"], 1))(grid), color=c_adapt, linestyle="-", linewidth=1.4, alpha=0.8)
    ax.set_ylim(2.0, 22.0)
    ax.set_xlabel(r"Microarchitectural Mahalanobis Shift Distance $d_{\mathrm{shift}}$")
    ax.set_ylabel("Inter-Token Latency MdAPE (%)")
    ax.set_title("(b) Error Stability Under Hardware Covariate Shift")
    ax.legend(loc="upper right", framealpha=0.92, fontsize=7.8)
    save_fig("fig3_accuracy_efficiency_panel.png")

    # ==========================================================================
    # FIGURE 4: Few-Shot Profiling & LLM Parameter Scalability (0.12B - 27B)
    # ==========================================================================
    print("Generating Figure 4...")
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 4.2))
    ax = axes[0]
    policy_styles = {
        "random": ("Uniform Random", "o", c_gray, "--"),
        "diversity": ("K-Means Diversity", "s", c_gold, "-."),
        "uncertainty": ("Max Uncertainty", "d", c_event, ":"),
        "regret_optimal": ("Boundary Heuristic (ROAA)", "^", c_adapt, "-"),
    }
    for pol, (label, marker, color, lstyle) in policy_styles.items():
        sub = df_fewshot[df_fewshot["policy"] == pol].sort_values("budget_k")
        ax.plot(sub["budget_k"], sub["mdape_itl"], marker=marker, markersize=6, color=color, linestyle=lstyle, linewidth=1.8, label=label)
    ax.set_xticks([0, 1, 3, 5])
    ax.set_xlabel(r"Few-Shot Calibration Budget ($k$ probed configurations)")
    ax.set_ylabel("Inter-Token Latency MdAPE (%)")
    ax.set_title("(a) Few-Shot FiLM Adaptation vs. Zero-Shot Ensemble")
    ax.legend(loc="upper right", framealpha=0.92, fontsize=7.8)

    ax = axes[1]
    model_summary = df_preds.groupby("model").agg({
        "total_b_params": "first",
        "itl_true": lambda s: np.median(s) * 1000.0,
        "itl_pred_pican": lambda s: np.median(s) * 1000.0,
    }).sort_values("total_b_params")
    ax.scatter(model_summary["total_b_params"], model_summary["itl_true"], s=42, color=c_gray, alpha=0.75, edgecolors="black", label="Measured Median ITL")
    ax.plot(model_summary["total_b_params"], model_summary["itl_pred_pican"], color=c_adapt, linewidth=1.8, label="SHIFT-GPU Prediction")
    ax.set_xlabel("LLM Parameter Count (Billions: 0.12B–27B)")
    ax.set_ylabel("Median Inter-Token Latency (ms)")
    ax.set_title("(b) Model Scalability Across 42 Evaluated LLMs")
    ax.legend(loc="upper left", framealpha=0.92, fontsize=8)
    save_fig("fig4_computational_performance_panel.png")

    # ==========================================================================
    # FIGURE 5: Per-Architecture Error Distributions
    # ==========================================================================
    print("Generating Figure 5...")
    fig, axes = plt.subplots(1, 3, figsize=(11.5, 3.8))
    arch_subsets = [
        ("Ampere (A100 & A30)", ["A100 SXM4 40 GB", "A30 PCIe"]),
        ("Ada Lovelace (L40S & L4)", ["L40S", "L4"]),
        ("Hopper (H100 & H200)", ["H100 NVL 94 GB", "H200 NVL"]),
    ]
    for idx, (arch_name, gpu_list) in enumerate(arch_subsets):
        ax = axes[idx]
        sub = df_preds[df_preds["gpu_db_name"].isin(gpu_list)]
        e_x = np.abs(sub["itl_true"] - sub["itl_pred_xgb"]) / sub["itl_true"] * 100.0
        e_xr = np.abs(sub["itl_true"] - sub["itl_pred_xgb_roof"]) / sub["itl_true"] * 100.0
        e_p = np.abs(sub["itl_true"] - sub["itl_pred_pican"]) / sub["itl_true"] * 100.0
        pdata = pd.DataFrame({
            "Error (%)": np.concatenate([e_x, e_xr, e_p]),
            "Model": ["XGBoost"] * len(sub) + ["XGB+Roofline"] * len(sub) + ["SHIFT-GPU"] * len(sub),
        })
        sns.boxplot(
            x="Model", y="Error (%)", data=pdata, ax=ax,
            palette=[c_fixed, c_roofx, c_adapt], width=0.5,
            showmeans=True, meanprops={"marker": "D", "markerfacecolor": "white", "markeredgecolor": "black", "markersize": 4.5},
        )
        ax.set_yscale("log"); ax.set_ylim(0.4, 200)
        ax.set_xlabel("")
        ax.set_ylabel("Relative Error (%) [log scale]" if idx == 0 else "")
        ax.set_title(f"({chr(97+idx)}) {arch_name}", fontsize=9.8)
        ax.tick_params(axis="x", labelsize=8.2)
    save_fig("fig5_per_architecture_error_panel.png")

    # ==========================================================================
    # FIGURE 6: Cluster-Wide Cumulative Regret Across Tight, Moderate, Relaxed SLAs
    # Using exact Eq. (2) regret across identical 125 workloads over all 8 GPUs
    # ==========================================================================
    print("Generating Figure 6...")
    fig, axes = plt.subplots(1, 3, figsize=(11.5, 3.8))
    workloads = df_preds[["model", "scenario"]].drop_duplicates().reset_index(drop=True)
    unique_gpus = df_preds["gpu_db_name"].unique()
    lookup = {(r["model"], r["scenario"], r["gpu_db_name"]): r for _, r in df_preds.iterrows()}

    for i, t_max in enumerate([0.020, 0.030, 0.035]):
        ax = axes[i]
        regs = {"min_tdp_roofline": [], "xgb_point": [], "xgb_roof_point": [], "shift_gpu_calibrated": []}
        for _, w in workloads.iterrows():
            m, sc = w["model"], w["scenario"]
            orac = [lookup[(m, sc, g)]["power_true"] for g in unique_gpus if (m, sc, g) in lookup and lookup[(m, sc, g)]["itl_true"] <= t_max]
            p_or = min(orac) if orac else np.nan
            for pol, lat_k, pwr_k in [
                ("min_tdp_roofline", "itl_roofline", "thermal_design_power_w"),
                ("xgb_point", "itl_pred_xgb", "power_pred_xgb"),
                ("xgb_roof_point", "itl_pred_xgb_roof", "power_pred_xgb"),
                ("shift_gpu_calibrated", "itl_bound_upper", "power_pred_pican"),
            ]:
                cands = [
                    (g, lookup[(m, sc, g)][pwr_k])
                    for g in unique_gpus
                    if (m, sc, g) in lookup and lookup[(m, sc, g)][lat_k] <= t_max
                ]
                if cands:
                    cands.sort(key=lambda x: x[1])
                    r = lookup[(m, sc, cands[0][0])]
                    reg = 0.0 if np.isnan(p_or) else max(0.0, r["power_true"] - p_or)
                    if r["itl_true"] > t_max:
                        reg += 5.0 * r["power_true"]
                else:
                    reg = 50.0 if not np.isnan(p_or) else 0.0
                regs[pol].append(reg)

        req_x = np.arange(1, len(workloads) + 1)
        ax.plot(req_x, np.cumsum(regs["min_tdp_roofline"]), color="#b91c1c", linestyle=":", linewidth=1.6, label="Min-TDP (Roofline)")
        ax.plot(req_x, np.cumsum(regs["xgb_point"]), color=c_fixed, linestyle="--", linewidth=1.6, label="Matched XGBoost")
        ax.plot(req_x, np.cumsum(regs["xgb_roof_point"]), color=c_roofx, linestyle="-.", linewidth=1.5, label="XGBoost + Roofline")
        ax.plot(req_x, np.cumsum(regs["shift_gpu_calibrated"]), color=c_adapt, linewidth=2.0, label="SHIFT-GPU (Calibrated)")
        ax.set_xlabel("Evaluation Workload Index (1–125)")
        if i == 0:
            ax.set_ylabel("Cumulative Operational Regret (Eq. 2)")
        ax.set_title(f"({chr(97+i)}) Cluster Regret ($T_{{\\max}} = {int(t_max*1000)}$ ms)")
        ax.legend(loc="upper left", fontsize=7.3, framealpha=0.92)
    save_fig("fig6_cumulative_regret_panel.png")

    # ==========================================================================
    # FIGURE 7: Systematic Ablation & Clean Pareto Frontier (Zero Overlaps!)
    # ==========================================================================
    print("Generating Figure 7...")
    fig, axes = plt.subplots(1, 2, figsize=(11.2, 4.3))
    ax = axes[0]
    label_map = {
        "Full": "Full\nSHIFT-GPU",
        "Ablation B": "Flat MLP\n+ Roofline",
        "Baseline C": "XGBoost\n+ Roofline",
        "Baseline D": "Matched\nXGBoost",
        "Ablation A": "Pure Attn.\n(No Roofline)",
    }
    ordered_keys = ["Full", "Ablation B", "Baseline C", "Baseline D", "Ablation A"]
    bar_labels = [label_map[k] for k in ordered_keys]
    bar_vals = [df_ablation[df_ablation["model_variant"].str.contains(k, regex=False)]["MdAPE_ITL"].iloc[0] for k in ordered_keys]
    bar_colors = [c_adapt, c_gold, c_roofx, c_fixed, "#7f0000"]

    bars = ax.bar(bar_labels, bar_vals, color=bar_colors, edgecolor="black", linewidth=0.7, width=0.55)
    for bar in bars:
        h = bar.get_height()
        ax.text(bar.get_x() + bar.get_width() / 2.0, h + 0.6, f"{h:.2f}%", ha="center", va="bottom", fontsize=8.2, weight="bold")
    ax.set_ylabel("Zero-Shot LOGO MdAPE (%)")
    ax.set_title("(a) Architecture & Physics Component Ablations")
    ax.set_ylim(0, max(bar_vals) * 1.18)
    ax.tick_params(axis="x", labelsize=8.0)

    ax = axes[1]
    pol_plot = df_rec[df_rec["policy"] != "min_tdp_naive"].copy()
    pol_meta = {
        "oracle": ("True Oracle", c_event, "*", (-24, 24), 4, 150),
        "xgb_point": ("XGBoost Point", c_fixed, "o", (16, 10), 4, 100),
        "xgb_roof_point": ("XGB + Roofline", c_roofx, "s", (12, 24), 4, 100),
        "pican_point": ("PICAN Point", "#fb923c", "^", (-55, 22), 3, 115),
        "shift_gpu_calibrated": ("SHIFT-GPU (Calibrated)", c_adapt, "D", (-15, 42), 5, 95),
        "min_tdp_roofline": ("Min-TDP (Roofline)", "#b91c1c", "X", (10, -4), 4, 120),
    }
    for _, row in pol_plot.iterrows():
        pk = row["policy"]
        name, col, mk, offset, zord, sz = pol_meta.get(pk, (pk, c_gray, "o", (8, 8), 4, 110))
        pwr, viol = row["mean_power_watts"], row["violation_rate_pct"]
        # Slight horizontal jitter only for visual separation if overlapping exactly? Wait: don't alter coordinates! Just marker size & label offset.
        ax.scatter(pwr, viol, s=sz, color=col, marker=mk, edgecolors="black", linewidth=0.9, zorder=zord)
        ax.annotate(
            name, xy=(pwr, viol), textcoords="offset points", xytext=offset,
            fontsize=8.0, weight="bold" if "SHIFT-GPU" in name else "normal",
            arrowprops=dict(arrowstyle="-", color="gray", lw=0.7, shrinkA=0, shrinkB=4),
            zorder=6,
        )
    ax.set_xlabel("Mean Selected Cluster Power Draw (Watts)")
    ax.set_ylabel("Latency SLA Violation Rate (%) at 35 ms")
    ax.set_title("(b) Production Hardware Selection: SLA Risk vs. Power")
    ax.set_xlim(99.5, 121.5)
    ax.set_ylim(-1.2, 11.5)
    save_fig("fig7_summary_heatmap.png")

    print("All publication figures regenerated cleanly!")


if __name__ == "__main__":
    main()
